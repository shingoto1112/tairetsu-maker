#!/usr/bin/env node

import { readFileSync } from "node:fs";
import path from "node:path";

const migrationFiles = [
  "20260514000000_cloud_collaboration_foundation.sql",
  "20260514001000_cloud_collaboration_sharing_realtime.sql",
  "20260514002000_cloud_project_owner_operations.sql",
  "20260514005000_cloud_collaboration_private_display_names.sql",
  "20260514006000_cloud_project_delete_hide.sql",
  "20260514007000_cloud_owner_takeover_requests.sql",
  "20260514008000_cloud_display_name_repair.sql",
  "20260515000000_cloud_contacts.sql",
  "20260515001000_cloud_scene_cell_locks.sql",
];

const now = new Date().toISOString();
const chunks = [
  "-- Tairetsu Maker cloud collaboration Supabase setup SQL",
  `-- Generated by scripts/cloud-collab-sql.mjs at ${now}`,
  "-- Paste this whole output into Supabase SQL Editor and run it once.",
  "-- Do not paste service_role keys into the frontend or Vercel.",
  "",
  "-- Re-running older migrations can change table-returning function shapes.",
  "-- Drop them first so CREATE OR REPLACE does not fail on return type changes.",
  "drop function if exists public.list_project_collaboration(uuid);",
  "drop function if exists public.list_user_contacts();",
  "drop function if exists public.add_contact_by_email(text);",
  "drop function if exists public.add_project_member_from_contact(uuid, uuid, text);",
  "drop function if exists public.add_project_member_to_contacts(uuid, uuid);",
  "drop function if exists public.cloud_collab_display_name_for_user(uuid);",
  "drop function if exists public.save_scene_cell_patch_with_lock(uuid, text, text, text, jsonb, text, integer, text);",
  "drop function if exists public.cloud_collab_scene_cell_scene_id(text);",
  "drop function if exists public.cloud_collab_scene_cell_target_id(text, text, text);",
  "",
];

for (const fileName of migrationFiles) {
  const filePath = path.resolve("supabase", "migrations", fileName);
  chunks.push("");
  chunks.push("-- ==================================================================");
  chunks.push(`-- ${fileName}`);
  chunks.push("-- ==================================================================");
  chunks.push("");
  chunks.push(readFileSync(filePath, "utf8").trimEnd());
  chunks.push("");
}

process.stdout.write(`${chunks.join("\n")}\n`);
